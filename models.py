"""Pydantic validates incoming JSON before the endpoint uses it."""
from pydantic import BaseModel, ConfigDict, EmailStr, Field


class StudentInput(BaseModel):
    """Required fields for creation and full replacement with PUT."""
    # Trim spaces and reject unexpected fields, including a client-supplied ID.
    model_config = ConfigDict(str_strip_whitespace=True, extra="forbid")
    name: str = Field(min_length=3, max_length=50, examples=["Asha"])
    email: EmailStr = Field(examples=["asha@example.com"])
    # Match the class's age rule: greater than 18 and less than 100.
    # strict=True rejects booleans, fractions, and quoted numbers.
    age: int = Field(gt=18, lt=100, strict=True, examples=[22])
    course: str = Field(min_length=2, max_length=100, examples=["Python"])


class Student(StudentInput):
    """Response includes the ID generated by PostgreSQL."""
    id: int = Field(gt=0)


class DeleteResult(BaseModel):
    message: str
    student_id: int
